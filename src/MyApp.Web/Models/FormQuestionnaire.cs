    private static FormQuestionnaireSection Section(
        int number,
        string title,
        bool repeatable,
        params FormQuestion[] questions) =>
        new(number, title, repeatable, questions);

    private static FormQuestion Q(string key, string label, FormQuestionType type = FormQuestionType.Text) =>
        new(key, label, type);

    private static FormQuestion L(string key, string label) => Q(key, label, FormQuestionType.LongText);
    private static FormQuestion D(string key, string label) => Q(key, label, FormQuestionType.Date);
    private static FormQuestion N(string key, string label) => Q(key, label, FormQuestionType.Number);
    private static FormQuestion E(string key, string label) => Q(key, label, FormQuestionType.Email);
    private static FormQuestion Y(string key, string label) => Q(key, label, FormQuestionType.YesNo);

    private static FormQuestion ConditionalOnYes(string key, string label, FormQuestionType type = FormQuestionType.Text) =>
        new(key, label, type, DependsOnKey: "hasOtherFamilyMembers", DependsOnValue: "Yes");

    private static IReadOnlyList<string> GetCountryOptions() =>
        CultureInfo.GetCultures(CultureTypes.SpecificCultures)
            .Select(culture => (Culture: culture, RegionCode: culture.Name[(culture.Name.LastIndexOf('-') + 1)..]))
            .Where(item => item.RegionCode.Length == 2 && item.RegionCode.All(char.IsLetter))
            .Select(item => new RegionInfo(item.Culture.Name))
            .GroupBy(region => region.TwoLetterISORegionName, StringComparer.Ordinal)
            .Select(group => group.First().EnglishName)
            .OrderBy(name => name, StringComparer.CurrentCulture)
            .ToArray();
